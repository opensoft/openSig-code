const HOST_PREFIXES = [
  [REPO, '<repo>'],
  [tmpdir(), '<tmp>'],
  [homedir(), '<home>'],
]
  .filter(([path]) => typeof path === 'string' && path.length > 1)
  .sort((a, b) => b[0].length - a[0].length);

/**
 * Text as a message or a first-error record may hold it: no URL query or fragment, no invitation
 * parameter, no cookie value, no compact token, no long opaque run, and no host path.
 */
export function scrub(value) {
  let text = String(value);
  text = text.replace(/(\bhttps?:\/\/[^\s?#'"`<>()]*)[?#][^\s'"`<>()]*/g, '$1<redacted>');
  text = text.replace(/([#?&]i=)[A-Za-z0-9_-]+/g, '$1<redacted>');
  text = text.split(`${COOKIE_NAME}=`).map((piece, index) => (index === 0 ? piece : piece.replace(/^[^;\s"']*/, '<redacted>'))).join(`${COOKIE_NAME}=`);
  text = text.replace(/\beyJ[A-Za-z0-9_-]*\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]*/g, '<redacted>');
  for (const [prefix, word] of HOST_PREFIXES) text = text.split(prefix).join(word);
  text = text.replace(/\bfile:\/\/\S*/g, '<abs>');
  text = text.replace(/(?<![\w.>~-])\/(?!v1\/|sign\b)[A-Za-z0-9_.~@+-]+(?:\/[^\s'"`()<>,;]*)?/g, '<abs>');
  return text.replace(/(?<![A-Za-z0-9_-])(?![0-9a-f]+(?![A-Za-z0-9_-]))[A-Za-z0-9_-]{40,}(?![A-Za-z0-9_-])/g, '<redacted>');
}

const FORBIDDEN_IN_RECORDS = Object.freeze([
  [/https?:\/\//i, 'a URL'],
  [/\/sign\b/, 'the review shell path'],
  [/[#?&]i=/, 'an invitation parameter'],
  [/__Host-/, 'the session cookie name'],
  [/-----BEGIN/, 'PEM armour'],
  [/\beyJ[A-Za-z0-9_-]+\./, 'a compact token'],
  [/@/, 'an address'],
  [/"\/[^"]*"/, 'an absolute path'],
]);

/** A record's text holds no secret, token, link or host path (request #48 C1; the T017 line). */
export function assertRecordClean(text, what) {
  for (const [pattern, label] of FORBIDDEN_IN_RECORDS) assert.doesNotMatch(text, pattern, `${what} holds ${label}`);
  for (const [prefix] of HOST_PREFIXES) assert.equal(text.includes(prefix), false, `${what} holds a host path`);
}

