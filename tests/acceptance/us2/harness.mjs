// § Case catalogs SC-001 and SC-005; the T017 line with A-010 requests #48 (C1), #56 and #76 (3)).
// It follows T011's US1 pattern: one composed server per test file, started in this process with
// the real entrypoint startServer() on plain http://127.0.0.1 and an OS-chosen port, every
// operator step through the contract's operator routes with a bearer token, and every recipient
// step of an SC001 flow through the locked browser (browser.mjs). It imports production modules,
// T035's build entry and exactly one other test module, read-only and named by the spec:
// - tests/contract/envelopes/lib/schema.mjs, with its sibling contract.mjs for the vendored
//   document, the test-local contract validator (request #76 (3), row T016-NOTES F3).
// It imports no oracle module. T014's read-only oracle adapter and agreement helper (request
// #78 (1)) are reached only through oracle.mjs, which each file that records evidence imports and
// binds here (bindOracleLabels), so a file that runs no oracle, [US2-ANCHOR-CONTROL], loads in a
// tree without the oracle's directory ([US2-STATIC] pins this).
// Everything is synthetic and made at test runtime in owner-only mkdtemp directories (0700) that
// close() removes:
// - the review shell, built by T035's builder into a temporary directory (StartOptions.distDir);
// - a migrated SQLite database with the synthetic alpha tenant and a consent text in force;
// - the operator authentication file: an ES256 key generated now, tokens signed per request,
//   carrying artifacts:read beside the envelope scopes;
// - the challenge-HMAC key file and the mail spool;
// - the development seal: an RSA-3072 key (exponent 65537) generated by node:crypto and written
//   once at 0600, and a self-signed certificate made from it by `openssl req -x509` with a config
//   file of this harness's own, so the host's openssl.cnf is never read;
// - an unrelated synthetic anchor certificate, the only content of OPENSIG_TRUST_ANCHORS_FILE. Its
//   key is removed as soon as the certificate exists. Every flow's trust is therefore judged
//   against a real anchor set, and must read `untrusted` for the development certificate.
//   [US2-ANCHOR-CONTROL] (trust-anchor-control.test.mjs, which the frozen runner's sorted, serial
//   order runs last, after the SC005-02 burst) alone starts its world with anchors
//   'seal-certificate' (A-010 request #88 item 2, N2): its anchors file then holds exactly its own
//   seal certificate's PEM, and no unrelated anchor is made. Every other world keeps the unrelated
//   anchor (the default).
// The composed server (code 7257167 with the T031 US2 composition slot; the T031 line's requests
// #81 and #86 notes; row ARTIFACT-ROUTES), as this harness relies on it:
// - startServer(env, { logSink, distDir }) is the only entry point used: no new StartOptions member.
//   Its US2 startup checks (src/server/finalization.ts) run before anything is composed: T015's
//   fault-hook flag in this process's argv is refused (request #86 (4)); KEY-02 refuses PEM key text
//   in this process's environment or arguments; the seal key file (absolute path, owner-only, 1 to
//   16384 bytes) is opened through T038's openSealKey with nothing read; the certificate file holds
//   exactly one PEM CERTIFICATE that T013 accepts (RSA-3072, exponent 65537); the anchors file holds
//   1 to maxAnchors certificates that T014's parseAnchors accepts. With the pair set, ROUTES carries
//   T016's and T038's handlers and T038's FinalizationRunner starts once at its default interval,
//   DEFAULT_RUN_INTERVAL_MS (15 s), claiming at most 10 jobs per tenant per run and running them
//   one attempt at a time. close() awaits the runner's stop() right after the listeners close.
// - This harness never passes the fault-hook flag: it adds no argument to any process, it checks
//   that its own argv and execArgv carry none before it starts the server (the server would refuse
//   it anyway), and it asserts that the composition has a runner and exactly the one anchor.
// - An envelope in `finalizing` completes with no outside trigger, at the runner's next tick;
//   readEnvelope then carries `artifact` (src/domain/envelopes/views.ts: completed_at is the publish
