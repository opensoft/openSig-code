let contractDoc = null;
/** The vendored contract, checked against its source record here (us2-local declares no `contract: true`). */
function contract() {
  if (contractDoc === null) {
    const loaded = loadVendoredContract();
    assert.equal(loaded.sha256, loaded.source.sha256, `the vendored contract matches its source record (${loaded.sha256.slice(0, 12)}, recorded ${String(loaded.source.sha256).slice(0, 12)})`);
    contractDoc = loaded.doc;
  }
  return contractDoc;
}

/**
 * Open a downloaded package: its five entries, and for each JSON member its parsed value, its
 * contract-schema errors (tests/contract/envelopes/lib/schema.mjs validate()), and whether its
 * bytes are their own RFC 8785 form. Nothing is asserted about the members here; the flow does.
 */
export function openPackage(zipBytes) {
  const entries = readStoredZip(zipBytes);
  const names = [...entries.keys()].sort();
  assert.deepEqual(names, [...PACKAGE_NAMES], `the package holds exactly the five members (found ${names.join(', ')})`);
  const members = {};
  for (const member of JSON_MEMBERS) {
    const bytes = entries.get(member.name);
    const text = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(bytes);
    const value = JSON.parse(text);
    const schema = contract().components.schemas[member.schema];
    assert.ok(schema, `the vendored contract defines ${member.schema}`);
    members[member.name] = { ...member, bytes, value, errors: validate(contract(), schema, value), isCanonical: canonicalJson(value) === text };
  }
  return { entries, members };
}

/** approval_evidence_digest: SHA-256 of the RFC 8785 form of the manifest without final_pdf_digest (data-model.md § FinalArtifact). */
export function evidenceDigestOf(manifest) {
  const { final_pdf_digest: _excluded, ...rest } = manifest;
  return sha256(Buffer.from(canonicalJson(rest), 'utf8'));
}

/**
 * A packaged ApprovalRecord's own digests, recomputed from its members with T017's serializer
 * (data-model.md § Entities, Approval; A-010 request #85 and row FV-DIGEST):
 * - field_values_digest = SHA-256 of the RFC 8785 form of {field_values, date_values};
 * - date_values: one {key, value} per date field of field_values, sorted by key, each value the UTC
 *   date of the record's server_time (derived, never stored);
 * - approval_digest = SHA-256 of the RFC 8785 form of the record without approval_digest.
 * Returns { fieldValuesDigest, approvalDigest, dateValues } as recomputed; the flow compares them.
 */
export function approvalRecordDigests(record) {
  const date = new Date(Date.parse(record.server_time)).toISOString().slice(0, 10);
  const dateValues = (Array.isArray(record.field_values) ? record.field_values : [])
    .filter((value) => value !== null && typeof value === 'object' && value.type === 'date')
    .map((value) => String(value.key))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
    .map((key) => ({ key, value: date }));
  const { approval_digest: _excluded, ...rest } = record;
  return {
    fieldValuesDigest: sha256(Buffer.from(canonicalJson({ field_values: record.field_values, date_values: record.date_values }), 'utf8')),
    approvalDigest: sha256(Buffer.from(canonicalJson(rest), 'utf8')),
    dateValues,
  };
}

