/**
 * The entries of a stored ZIP (ZIP-03: method 0, no comment, no data descriptor), by T017's own
 * reader: the end record, the central directory, each local header, each CRC-32 (node:zlib).
 */
export function readStoredZip(input) {
  const zip = Buffer.from(input);
  assert.ok(zip.length >= 22, `the package can hold a ZIP end record (${zip.length} bytes)`);
  const end = zip.length - 22;
  assert.equal(zip.readUInt32LE(end), 0x06054b50, 'the package ends with an end-of-central-directory record and no comment');
  assert.equal(zip.readUInt16LE(end + 4), 0, 'one disk');
  assert.equal(zip.readUInt16LE(end + 6), 0, 'the central directory is on disk 0');
  const count = zip.readUInt16LE(end + 10);
  assert.equal(zip.readUInt16LE(end + 8), count, 'every entry is on this disk');
  const directorySize = zip.readUInt32LE(end + 12);
  const directoryOffset = zip.readUInt32LE(end + 16);
  assert.equal(directoryOffset + directorySize, end, 'the central directory ends where the end record starts');
  const entries = new Map();
  let at = directoryOffset;
  for (let index = 0; index < count; index += 1) {
    assert.equal(zip.readUInt32LE(at), 0x02014b50, `central header ${index} carries its signature`);
    const flags = zip.readUInt16LE(at + 8);
    const method = zip.readUInt16LE(at + 10);
    const crc = zip.readUInt32LE(at + 16);
    const compressed = zip.readUInt32LE(at + 20);
    const size = zip.readUInt32LE(at + 24);
    const nameLength = zip.readUInt16LE(at + 28);
    const extraLength = zip.readUInt16LE(at + 30);
    const commentLength = zip.readUInt16LE(at + 32);
    const local = zip.readUInt32LE(at + 42);
    const name = zip.subarray(at + 46, at + 46 + nameLength).toString('utf8');
    assert.equal(method, 0, `${name}: stored, not compressed`);
    assert.equal(flags & ~0x0800, 0, `${name}: no flag but the UTF-8 name flag (flags ${flags})`);
    assert.equal(compressed, size, `${name}: stored size equals its size`);
    assert.equal(zip.readUInt32LE(local), 0x04034b50, `${name}: its local header carries its signature`);
    const localNameLength = zip.readUInt16LE(local + 26);
    const localExtraLength = zip.readUInt16LE(local + 28);
    assert.equal(zip.subarray(local + 30, local + 30 + localNameLength).toString('utf8'), name, `${name}: the local header names the same entry`);
    const start = local + 30 + localNameLength + localExtraLength;
    const data = zip.subarray(start, start + size);
    assert.equal(data.length, size, `${name}: all ${size} bytes are inside the package`);
    assert.equal(crc32(data) >>> 0, crc, `${name}: its CRC-32 matches`);
    assert.equal(entries.has(name), false, `${name}: named once`);
    entries.set(name, Buffer.from(data));
    at += 46 + nameLength + extraLength + commentLength;
  }
  assert.equal(at, end, 'the central directory holds exactly the counted entries');
  return entries;
}

/** RFC 8785 for the JSON values the package holds, written test-locally (never src/domain/canonical/). */
export function canonicalJson(value) {
  if (value === null || typeof value === 'boolean' || typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number') {
    assert.ok(Number.isFinite(value), 'canonical JSON holds finite numbers only');
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  assert.equal(typeof value, 'object', 'canonical JSON holds JSON values only');
  return `{${Object.keys(value)
    .sort()
    .map((name) => `${JSON.stringify(name)}:${canonicalJson(value[name])}`)
    .join(',')}}`;
}

