/** One HTTP/1.1 request to 127.0.0.1:port: { status, headers, json, bytes, ms }. */
export function http(port, { method = 'GET', path, headers = {}, body } = {}) {
  return new Promise((resolveResponse, reject) => {
    const payload = body === undefined ? undefined : Buffer.isBuffer(body) ? body : Buffer.from(typeof body === 'string' ? body : JSON.stringify(body));
    const sent = { ...headers };
    if (payload !== undefined) {
      sent['content-type'] ??= 'application/json';
      sent['content-length'] = String(payload.length);
    }
    const started = performance.now();
    const req = request({ host: '127.0.0.1', port, method, path, headers: sent, agent: false }, (res) => {
      const chunks = [];
      res.on('data', (chunk) => chunks.push(chunk));
      res.on('error', reject);
      res.on('end', () => {
        const bytes = Buffer.concat(chunks);
        let json = null;
        try {
          json = JSON.parse(bytes.toString('utf8'));
        } catch {
          json = null;
        }
        resolveResponse({ status: res.statusCode, headers: res.headers, json, bytes, ms: performance.now() - started });
      });
    });
    req.on('error', reject);
    req.setTimeout(60_000, () => req.destroy(new Error(`no answer to ${method} ${path} within 60 s`)));
    if (payload !== undefined) req.write(payload);
    req.end();
  });
}

/** Run the OpenSSL CLI (a us2-local capability) with only PATH in its environment. It fails; it never skips. */
export function openssl(args, cwd) {
  const run = spawnSync('openssl', args, { cwd, encoding: 'utf8', timeout: 60_000, env: { PATH: process.env.PATH ?? '' } });
  assert.equal(run.error, undefined, `openssl could not run (${run.error?.code ?? ''}); the runner probed it, so this is a failure, never a skip`);
  assert.equal(run.status, 0, `openssl ${args[0]} exits 0, not ${run.status}: ${scrub(run.stderr ?? '').slice(0, 400)}`);
  return run.stdout;
}

function opensslConfig(dir, name, commonName, extensions) {
  const path = join(dir, `${name}.cnf`);
  writeOwnerOnly(path, ['[req]', 'distinguished_name = dn', 'prompt = no', 'x509_extensions = ext', '[dn]', `CN = ${commonName}`, 'O = example.test', '[ext]', ...extensions, ''].join('\n'));
  return path;
}

/** The two anchor configurations a world can have; 'unrelated' is every world's but one. */
export const ANCHOR_MODES = Object.freeze(['unrelated', 'seal-certificate']);

/**
 * The development seal and the configured anchor, in `dir` (owner-only). Key files are written
 * once at 0600 and reach OpenSSL by path only; no key text is ever put in the environment or argv.
 * - anchors 'unrelated' (the default): a fresh unrelated anchor, whose key is removed at once;
 * - anchors 'seal-certificate' ([US2-ANCHOR-CONTROL] only; A-010 request #88 item 2, N2): the
 *   anchors file holds exactly the seal certificate's PEM bytes, the matching anchor. By
 *   src/verifier/trust.ts a signer byte-identical to a configured anchor is trusted directly
 *   (detail anchor-direct, trust_anchor_ref the anchor's DER SHA-256).
 */
function developmentMaterial(dir, anchors) {
  const seal = generateKeyPairSync('rsa', { modulusLength: 3072, publicExponent: 0x10001 });
  const sealKeyFile = join(dir, 'seal-key.pem');
  writeOwnerOnly(sealKeyFile, seal.privateKey.export({ type: 'pkcs8', format: 'pem' }));
  const sealCertFile = join(dir, 'seal-cert.pem');
  const sealConfig = opensslConfig(dir, 'seal', 'openSig synthetic development seal', ['basicConstraints = critical,CA:FALSE', 'keyUsage = critical,digitalSignature,nonRepudiation']);
  openssl(['req', '-x509', '-new', '-key', sealKeyFile, '-sha256', '-days', '2', '-config', sealConfig, '-out', sealCertFile], dir);
  chmodSync(sealCertFile, 0o600);

  const anchorsFile = join(dir, 'anchors.pem');
  if (anchors === 'seal-certificate') {
    writeOwnerOnly(anchorsFile, readFileSync(sealCertFile));
  } else {
    const anchor = generateKeyPairSync('ec', { namedCurve: 'P-256' });
    const anchorKeyFile = join(dir, 'anchor-key.pem');
    writeOwnerOnly(anchorKeyFile, anchor.privateKey.export({ type: 'pkcs8', format: 'pem' }));
    const anchorConfig = opensslConfig(dir, 'anchor', 'openSig synthetic unrelated anchor', ['basicConstraints = critical,CA:TRUE', 'keyUsage = critical,keyCertSign,cRLSign']);
    openssl(['req', '-x509', '-new', '-key', anchorKeyFile, '-sha256', '-days', '2', '-config', anchorConfig, '-out', anchorsFile], dir);
    rmSync(anchorKeyFile);
    chmodSync(anchorsFile, 0o600);
  }

  const sealPem = readFileSync(sealCertFile, 'utf8');
  const anchorPem = readFileSync(anchorsFile, 'utf8');
  const sealCertificate = new X509Certificate(sealPem);
  const anchorCertificate = new X509Certificate(anchorPem);
  assert.equal(sealCertificate.publicKey.asymmetricKeyDetails?.modulusLength, 3072, 'the development seal certificate carries an RSA-3072 key');
  assert.equal(sealCertificate.issuer, sealCertificate.subject, 'the development seal certificate is self-signed');
  if (anchors === 'seal-certificate') {
    assert.equal(anchorPem, sealPem, 'the matching anchor is the seal certificate, byte for byte');
  } else {
    assert.notEqual(sha256(anchorCertificate.raw), sha256(sealCertificate.raw), 'the configured anchor is not the seal certificate');
  }
  return {
    anchors,
    sealKeyFile,
    sealCertFile,
    anchorsFile,
    sealPem,
    anchorPem,
    sealCertificateSha256: sha256(sealCertificate.raw),
    anchorCertificateSha256: sha256(anchorCertificate.raw),
    opensslVersion: openssl(['version'], dir).trim(),
  };
}

