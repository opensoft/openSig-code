        assert.equal(uploaded.status, 200, `${flow}: uploadDocument answers 200 through T033's parse service, not ${uploaded.status} (${uploaded.json?.code ?? ''})`);
        assert.equal(uploaded.json.document.digest, entry.sha256, `${flow}: the stored document is the fixture ${document}`);
