/** Nearest-rank percentile of `values` (milliseconds). */
export function percentile(values, p) {
  assert.ok(values.length > 0, 'a percentile needs at least one value');
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.max(0, Math.ceil((p / 100) * sorted.length) - 1)];
}

/** { n, p50_ms, p95_ms, max_ms }, rounded to 0.1 ms. */
export function summarize(values) {
  const round = (ms) => Math.round(ms * 10) / 10;
  return { n: values.length, p50_ms: round(percentile(values, 50)), p95_ms: round(percentile(values, 95)), max_ms: round(Math.max(...values)) };
}
